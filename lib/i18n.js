export function detectLang(text) {
  if (!text || typeof text !== "string") return null;
  if (/[ঀ-৿]/.test(text)) return "bn"; // Bengali script
  if (/[ऀ-ॿ]/.test(text)) return "hi"; // Devanagari
  if (/[぀-ヿ]/.test(text)) return "ja"; // Japanese kana (hiragana/katakana)
  if (/[가-힯]/.test(text)) return "ko"; // Korean Hangul
  if (/[؀-ۿ]/.test(text)) return "ar"; // Arabic
  if (/[一-鿿]/.test(text)) return "zh"; // CJK / Chinese (kana already handled above)
  const count = (words) => { let c = 0; for (const w of words) { if (new RegExp("(^|[^a-zäöüßàáâçèéêëíîïñóôõúùûãœ])" + w + "($|[^a-zäöüßàáâçèéêëíîïñóôõúùûãœ])", "i").test(text)) c++; } return c; };
  const scores = {
    es: count(ES_WORDS) + (/[¿¡ñ]/i.test(text) ? 2 : 0),
    hi: count(HI_WORDS),
    de: count(DE_WORDS) + (/[äöüß]/i.test(text) ? 2 : 0),
    fr: count(FR_WORDS) + (/[àâçèêëîïôùûœ]/i.test(text) ? 1 : 0),
    pt: count(PT_WORDS) + (/[ãõ]/i.test(text) ? 2 : 0),
    en: count(EN_WORDS),
  };
  const [bestLang, bestScore] = Object.entries(scores).sort((a, b) => b[1] - a[1])[0];
  return bestScore >= 2 ? bestLang : null; // unsure → stay in current language
}

