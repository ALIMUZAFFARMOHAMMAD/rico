// ---- language preference: "auto" (default) or a fixed code ----

export function getStoredPref() {
  if (typeof window === "undefined") return "auto";
  const l = window.localStorage.getItem("hitony_lang");
  return LANGS[l] ? l : "auto";
}

export function storePref(v) {
  if (typeof window === "undefined") return;
  if (v === "auto" || LANGS[v]) { window.localStorage.setItem("hitony_lang", v); window.dispatchEvent(new Event("rico-lang")); }
}

// Whether a language code reads right-to-left (Arabic, etc.)
export const isRTL = (code) => !!(LANGS[code] && LANGS[code].rtl);

export function getDetectedLang() {
  if (typeof window === "undefined") return null;
  const l = window.localStorage.getItem("hitony_lang_detected");
  return LANGS[l] ? l : null;
}

export function storeDetectedLang(l) {
  if (typeof window !== "undefined" && LANGS[l]) { window.localStorage.setItem("hitony_lang_detected", l); window.dispatchEvent(new Event("rico-lang")); }
}

